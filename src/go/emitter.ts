/**
 * The `ServerBinding` members derived from a contract method.
 *
 * Both spellings are unexported, and neither can contain an underscore because
 * `exportedIdentifier` splits on every non-alphanumeric rune. That is the whole
 * of the collision argument for this type: the emitter's own members are either
 * exported — the public API, which a contract-derived member can never be — or
 * carry the `rpc_` prefix, which a contract-derived member can never carry.
 */
function listenerField(method: RpcMethod): string {
  return `listen${methodName(method)}`;
}

function handlerMethod(method: RpcMethod): string {
  return `handle${methodName(method)}`;
}

/**
 * `ServerBinding`'s own members.
 *
 * They share one namespace with the contract-derived `listen…`/`handle…`
 * members above, so every one of them lives in the reserved namespace. Spelling
 * them here rather than inline is what makes that reviewable: the invariant is
 * "this table, and nothing else, is what the emitter adds to the type", and it
 * holds without any reasoning about the shape of the names in it.
 */
const BINDING = {
  socket: generated("socket"),
  emitState: generated("emitState"),
  handler: generated("handler"),
  ctx: generated("ctx"),
  cancel: generated("cancel"),
  mu: generated("mu"),
  disposed: generated("disposed"),
  errorObserver: generated("errorObservers"),
  errorObserverSeq: generated("errorObserverSeq"),
  disposeOnce: generated("disposeOnce"),
  listenRpcError: generated("listenRpcError"),
  listenDisconnect: generated("listenDisconnect"),
  emitError: generated("emitError"),
  handleRpcError: generated("handleRpcError"),
  conn: generated("conn"),
} as const;

/**
 * The local a handler body binds one decoded argument to.
 *
 * Deliberately positional rather than the contract's parameter name: a handler
 * body is the one generated scope that would otherwise hold both the emitter's
 * locals and the contract's identifiers. Keeping the contract's names out of it
 * entirely makes the body immune to every collision at once — reserved words,
 * predeclared types, imported package names and the emitter's own helpers — and
 * costs nothing, because the readable names still appear in the `ServerHandler`
 * signature that developers actually implement against.
 */
function argumentLocal(index: number): string {
  return `arg${index}`;
}

function methodParameters(method: RpcMethod, q: string): string {
  return method.params.map((param) => `${paramName(param)} ${renderGoType(param.type, q)}`).join(", ");
}

function handlerParameters(method: RpcMethod, q: string): string {
  const params = methodParameters(method, q);
  return params ? `ctx context.Context, ${params}` : "ctx context.Context";
}

/**
 * The arguments a handler body forwards, bound to positional locals. The
 * context is the binding's on a side that cannot reconnect, where the binding
 * lives exactly as long as the connection; on one that can, it is the context
 * of the connection the call arrived on, handed to the body by its listener.
 */
function handlerCallArguments(method: RpcMethod, side: GoSide): string {
  const context = side.reconnects ? "ctx" : `b.${BINDING.ctx}`;
  return [context, ...method.params.map((_, index) => argumentLocal(index))].join(", ");
}

/** The arguments a client method forwards, using the contract's own names. */
function outboundArguments(method: RpcMethod): string {
  const params = method.params.map(paramName).join(", ");
  return params ? `, ${params}` : "";
}

/**
 * Emits `MarshalJSON` for a struct that has at least one required slice or map
 * field.
 *
 * A required `tags: string[]` is `[]string` in Go, whose zero value is nil, and
 * `encoding/json` writes nil as `null` — so a handler returning a zero-valued
 * struct would put `"tags": null` on the wire against a client whose generated
 * type says `string[]`. Normalizing here rather than at the reply site covers
 * every path a struct can travel: a bare result, an element of a returned slice,
 * a map value, or a field of an enclosing struct, whose own `MarshalJSON` calls
 * into this one.
 *
 * The conversion to a defined type strips the method set, so the inner
 * `json.Marshal` does not re-enter this function. It copies the struct, so the
 * normalization is never visible to the handler that returned the value.
 *
 * Optional and nullable fields are pointers and are left alone: for those the
 * contract genuinely admits null. Nil slices nested *inside* another slice or
 * map (`string[][]`, `Record<string, string[]>`) keep Go's nil, because
 * replacing them would write through the shared backing array into the caller's
 * own value.
 *
 * A struct whose own fields claim this method name is served by
 * `writeFieldNormalizer` instead, which reaches the same guarantee one level
 * down.
 */
function writeStructMarshaller(
  writer: GoWriter,
  declaredName: string,
  fields: readonly { name: string; empty: string }[],
): void {
  const plain = generated("plain");
  const copy = generated("copy");

  writer.line();
  writer.line("// MarshalJSON normalizes the required slice and map fields whose Go zero");
  writer.line("// value is nil, so a value that leaves them unset never reaches a client");
  writer.line("// typed for an array or an object as JSON null.");
  writer.block(`func (v ${declaredName}) MarshalJSON() ([]byte, error)`, () => {
    writer.line(`type ${plain} ${declaredName}`);
    writer.line(`${copy} := ${plain}(v)`);
    for (const field of fields) {
      writer.block(`if ${copy}.${field.name} == nil`, () => {
        writer.line(`${copy}.${field.name} = ${field.empty}`);
      });
    }
    writer.line(`return json.Marshal(${copy})`);
  });
}

/**
 * The methods the emitter can attach to a generated struct.
 *
 * `encoding/json` dictates the spelling, so this is the one namespace the
 * emitter shares with a contract that it cannot move into the `rpc_` prefix.
 * A field deriving one of these names therefore takes it: the struct loses the
 * method and gains `writeFieldNormalizer` in its place. Enums are not affected
 * — their `Valid`/`MarshalJSON`/`UnmarshalJSON` live on a string type that
 * carries no fields at all.
 */
const STRUCT_METHODS = new Set(["MarshalJSON"]);

/**
 * Emits the defined type one required slice or map field is spelled with when
 * its struct cannot carry `MarshalJSON`.
 *
 * The type keeps the field assignable from and to the plain Go type it wraps —
 * `[]string` and a defined type over `[]string` convert freely — so a handler
 * still writes `Weird{Tags: []string{"a"}}`. Converting back to that plain type
 * inside the marshaller drops the method set, so the inner `json.Marshal` does
 * not re-enter. Nothing is copied and nothing is mutated: the nil case answers
 * with the empty literal directly.
 */
function writeFieldNormalizer(
  writer: GoWriter,
  declaredName: string,
  field: { readonly name: string; readonly declared: string; readonly empty: string; readonly normalizer: string },
): void {
  writer.line();
  writer.line(`// ${field.normalizer} keeps ${declaredName}.${field.name} off the wire as JSON null.`);
  writer.line(`// ${declaredName} declares a field named after the marshaller, so the`);
  writer.line("// normalization Go would otherwise reach through the struct's own");
  writer.line("// MarshalJSON is spelled on the field's type instead.");
  writer.line(`type ${field.normalizer} ${field.declared}`);
  writer.line();
  writer.block(`func (v ${field.normalizer}) MarshalJSON() ([]byte, error)`, () => {
    writer.block("if v == nil", () => writer.line(`return json.Marshal(${field.empty})`));
    writer.line(`return json.Marshal(${field.declared}(v))`);
  });
}

/**
 * Emits the unexported runtime the generated callers and bindings share:
 * error normalization, the encodability check, and JSON decoding.
 *
 * The types package carries one copy. A client generated into its own package
 * cannot reach unexported identifiers across the package boundary, so it carries
 * its own, reaching the exported error type through `q`. Both copies are
 * `rpc_`-prefixed and live in different packages, so neither can collide.
 */
export function writeRuntimeHelpers(writer: GoWriter, q: string): void {
  writer.block(`func ${generated("errorFromError")}(err error, method string) *${q}RpcError`, () => {
    writer.line(`var rpcErr *${q}RpcError`);
    writer.block("if errors.As(err, &rpcErr) && rpcErr != nil", () => {
      writer.line("clone := *rpcErr");
      writer.line("clone.RPCError = true");
      writer.block('if clone.Method == ""', () => writer.line("clone.Method = method"));
      writer.line("return &clone");
    });
    writer.line(`return ${q}NewRpcError(${q}CodeInternalError, err.Error(), method, nil)`);
  });
  writer.line();
  writer.block(`func ${generated("errorFromPanic")}(value any, method string) *${q}RpcError`, () => {
    writer.line(`return ${q}NewRpcError(${q}CodeInternalError, fmt.Sprint(value), method, nil)`);
  });
  writer.line();
  writer.line("// A payload the JSON encoder refuses would be dropped by Socket.IO's write");
  writer.line("// path without an error anywhere, leaving the peer to wait out its own");
  writer.line("// timeout. Checking before the value is handed over turns that silence into");
  writer.line("// an immediate answer that names the offending value — the common cause");
  writer.line("// being a required string enum left at its zero value.");
  writer.block(`func ${generated("ensureEncodable")}(value any, method string) *${q}RpcError`, () => {
    writer.block("if _, err := json.Marshal(value); err != nil", () => {
      writer.line(
        `return ${q}NewRpcError(${q}CodeInternalError, fmt.Sprintf("cannot encode payload: %v", err), method, nil)`,
      );
    });
    writer.line("return nil");
  });
  writer.line();
  writer.block(`func ${generated("decodeValue")}(value any, target any) error`, () => {
    writer.line("encoded, err := json.Marshal(value)");
    writer.block("if err != nil", () => writer.line("return err"));
    writer.block("if err := json.Unmarshal(encoded, target); err != nil", () => writer.line("return err"));
    writer.line("return nil");
  });
  writer.line();
  writer.line("// decodeInto leaves target at its zero value when the payload does not fit,");
  writer.line("// so a failed call still yields the zero result a caller expects alongside");
  writer.line("// the error rather than a half-populated one.");
  writer.block(`func ${generated("decodeInto")}(value any, target any) error`, () => {
    writer.block(`if err := ${generated("decodeValue")}(value, target); err != nil`, () => {
      writer.line("pointer := reflect.ValueOf(target)");
      writer.block("if pointer.Kind() == reflect.Pointer && !pointer.IsNil()", () => {
        writer.line("pointer.Elem().Set(reflect.Zero(pointer.Elem().Type()))");
      });
      writer.line("return err");
    });
    writer.line("return nil");
  });
  writer.line();
  writer.block(`func ${generated("decodeRpcError")}(value any) (*${q}RpcError, bool)`, () => {
    writer.line(`var rpcErr ${q}RpcError`);
    writer.block(`if err := ${generated("decodeValue")}(value, &rpcErr); err != nil`, () =>
      writer.line("return nil, false"),
    );
    writer.block("if !rpcErr.RPCError", () => writer.line("return nil, false"));
    writer.line("return &rpcErr, true");
  });
}

function writeTypesFile(schema: RpcSchema, packageName: string): string {
  const writer = new GoWriter();
  const declarations: DeclarationScope = declarationsByName(schema);

  writer.line(GENERATED_HEADER.trimEnd());
  writer.line();
  writer.line(`package ${packageName}`);
  writer.line();
  writer.line("import (");
  writer.line('\t"encoding/json"');
  writer.line('\t"errors"');
  writer.line('\t"fmt"');
  writer.line('\t"reflect"');
  writer.line(")");
  writer.line();
  writer.line(`const RPCErrorEvent = ${goString(RPC_ERROR_EVENT)}`);
  writer.line();
  writer.line("type RpcErrorCode string");
  writer.line();
  writer.line("const (");
  writer.line('\tCodeTimeout         RpcErrorCode = "TIMEOUT"');
  writer.line('\tCodeDisposed        RpcErrorCode = "DISPOSED"');
  writer.line('\tCodeDisconnected    RpcErrorCode = "DISCONNECTED"');
  writer.line('\tCodeAborted         RpcErrorCode = "ABORTED"');
  writer.line('\tCodeInternalError   RpcErrorCode = "INTERNAL_ERROR"');
  writer.line('\tCodeInvalidArgument RpcErrorCode = "INVALID_ARGUMENT"');
  writer.line(")");
  writer.line();
  writer.block("type RpcError struct", () => {
    writer.line('RPCError bool         `json:"__rpcError"`');
    writer.line('Code     RpcErrorCode `json:"code"`');
    writer.line('Message  string       `json:"message"`');
    writer.line('Method   string       `json:"method,omitempty"`');
    writer.line('Data     any          `json:"data,omitempty"`');
  });
  writer.line();
  writer.block("func (e *RpcError) Error() string", () => {
    writer.block("if e == nil", () => writer.line('return "<nil>"'));
    writer.block('if e.Method == ""', () => writer.line('return fmt.Sprintf("%s: %s", e.Code, e.Message)'));
    writer.line('return fmt.Sprintf("%s (%s): %s", e.Code, e.Method, e.Message)');
  });
  writer.line();
  writer.block(
    "func NewRpcError(code RpcErrorCode, message string, method string, data any) *RpcError",
    () => writer.line("return &RpcError{RPCError: true, Code: code, Message: message, Method: method, Data: data}"),
  );
  writer.line();
  writer.block("func IsRpcError(err error) bool", () => {
    writer.line("var rpcErr *RpcError");
    writer.line("return errors.As(err, &rpcErr) && rpcErr != nil && rpcErr.RPCError");
  });
  writer.line();
  writeRuntimeHelpers(writer, "");

  for (const declaration of schema.declarations) {
    const declaredName = goTypeName(declaration.name);
    writer.line();

    if (declaration.kind === "alias") {
      writer.line(`type ${declaredName} = ${renderGoType(declaration.target)}`);
      continue;
    }

    if (declaration.kind === "enum") {
      writer.line(`type ${declaredName} string`);
      writer.line();
      writer.line("const (");
      const constants = declaration.values.map(
        (value) => `${declaredName}${exportedIdentifier(value)}`,
      );
      const constantWidth = Math.max(...constants.map((constant) => constant.length));
      for (const [index, value] of declaration.values.entries()) {
        writer.line(`\t${padGoColumn(constants[index]!, constantWidth)}${declaredName} = ${goString(value)}`);
      }
      writer.line(")");
      writer.line();
      writer.block(`func (v ${declaredName}) Valid() bool`, () => {
        writer.line("switch v {");
        writer.line(`case ${constants.join(", ")}:`);
        writer.line("\treturn true");
        writer.line("default:");
        writer.line("\treturn false");
        writer.line("}");
      });
      writer.line();
      writer.block(`func (v ${declaredName}) MarshalJSON() ([]byte, error)`, () => {
        writer.block("if !v.Valid()", () => {
          writer.line(`return nil, fmt.Errorf("invalid ${declaredName} %q", v)`);
        });
        writer.line("return json.Marshal(string(v))");
      });
      writer.line();
      writer.block(`func (v *${declaredName}) UnmarshalJSON(data []byte) error`, () => {
        writer.block("if v == nil", () => {
          writer.line(`return fmt.Errorf("cannot unmarshal ${declaredName} into nil receiver")`);
        });
        writer.line("var raw string");
        writer.block("if err := json.Unmarshal(data, &raw); err != nil", () => writer.line("return err"));
        writer.line(`candidate := ${declaredName}(raw)`);
        writer.block("if !candidate.Valid()", () => {
          writer.line(`return fmt.Errorf("invalid ${declaredName} %q", raw)`);
        });
        writer.line("*v = candidate");
        writer.line("return nil");
      });
      continue;
    }

    if (declaration.kind === "union") {
      throw new Error(`emitTypes: unvalidated declaration kind union (${declaration.name})`);
    }

    // A field can be named after the marshaller, and Go allows a type only one
    // member of a given name. Where the contract claims the struct's method
    // namespace, normalization moves down to the field's own type, which
    // `encoding/json` consults wherever the value travels — so the guarantee is
    // the same one the method gives, reached without the method.
    const claimsMethodNamespace = declaration.fields.some((field) =>
      STRUCT_METHODS.has(fieldName(field)),
    );
    const fields = declaration.fields.map((field) => {
      const declared = renderGoType(field.type);
      const empty = emptyCompositeLiteral(field.type, declarations);
      const normalizer =
        claimsMethodNamespace && empty !== undefined
          ? generated(`${localIdentifier(declaration.name)}_${fieldName(field)}`)
          : undefined;
      return {
        wireName: field.name,
        optional: unwrapOptionality(field.type).optional,
        name: fieldName(field),
        declared,
        type: normalizer ?? declared,
        empty,
        normalizer,
      };
    });
    const nilable = fields.filter(
      (field): field is typeof field & { empty: string } => field.empty !== undefined,
    );

    const nameWidth = Math.max(0, ...fields.map((field) => field.name.length));
    const typeWidth = Math.max(0, ...fields.map((field) => field.type.length));
    if (fields.length === 0) {
      writer.line(`type ${declaredName} struct{}`);
    } else {
      writer.block(`type ${declaredName} struct`, () => {
        for (const rendered of fields) {
          const omitempty = rendered.optional ? ",omitempty" : "";
          writer.line(
            `${padGoColumn(rendered.name, nameWidth)}${padGoColumn(rendered.type, typeWidth)}\`json:${goString(`${rendered.wireName}${omitempty}`)}\``,
          );
        }
      });
    }

    if (claimsMethodNamespace) {
      for (const field of nilable) {
        if (field.normalizer) writeFieldNormalizer(writer, declaredName, { ...field, normalizer: field.normalizer });
      }
    } else if (nilable.length > 0) {
      writeStructMarshaller(writer, declaredName, nilable);
    }
  }

  return writer.toString();
}

/**
 * Emits the interface a side implements, one `Handle…` method per inbound call.
 *
 * The prefix is what keeps `go vet` clean without narrowing it: a contract may
 * name a method `scan` or `marshalJSON`, and `stdmethods` would object to the
 * bare name on any type at all. See `HANDLER_METHOD_PREFIX`.
 */
export function writeHandlerInterface(writer: GoWriter, side: GoSide, methods: readonly RpcMethod[]): void {
  if (methods.length === 0) {
    writer.line(`type ${side.handlerType} interface{}`);
    return;
  }
  writer.block(`type ${side.handlerType} interface`, () => {
    for (const method of methods) {
      const resultType = resultGoType(method, side.apiQ);
      const result = resultType ? ` (${resultType}, error)` : " error";
      writer.line(`${handlerInterfaceMethod(method)}(${handlerParameters(method, side.apiQ)})${result}`);
    }
  });
}

export function writeSocketEmitState(writer: GoWriter, side: GoSide): void {
  const state = generated("socketEmitState");
  const states = generated("socketEmitStates");

  writer.line("// Socket.IO carries the ack timeout as a flag mutated on the socket and");
  writer.line("// consumed by the next Emit, so two concurrent calls on one connection can");
  writer.line("// steal each other's timeout. Every emit the generated code performs is");
  writer.line("// serialized through the per-socket lock below to keep that pairing intact.");
  writer.block(`type ${state} struct`, () => {
    writer.line("mu   sync.Mutex");
    writer.line("refs int");
  });
  writer.line();
  writer.line(`var ${states} = struct {`);
  writer.line("\tsync.Mutex");
  writer.line(`\tstates map[${side.socketType}]*${state}`);
  writer.line(`}{states: make(map[${side.socketType}]*${state})}`);
  writer.line();
  writer.block(`func ${generated("acquireSocketEmitState")}(rawSocket ${side.socketType}) *${state}`, () => {
    writer.line(`${states}.Lock()`);
    writer.line(`defer ${states}.Unlock()`);
    writer.line(`shared := ${states}.states[rawSocket]`);
    writer.block("if shared == nil", () => {
      writer.line(`shared = &${state}{}`);
      writer.line(`${states}.states[rawSocket] = shared`);
    });
    writer.line("shared.refs++");
    writer.line("return shared");
  });
  writer.line();
  writer.block(
    `func ${generated("releaseSocketEmitState")}(rawSocket ${side.socketType}, shared *${state})`,
    () => {
      writer.block("if rawSocket == nil || shared == nil", () => writer.line("return"));
      writer.line(`${states}.Lock()`);
      writer.line(`defer ${states}.Unlock()`);
      writer.block(`if ${states}.states[rawSocket] != shared`, () => writer.line("return"));
      writer.line("shared.refs--");
      writer.block("if shared.refs == 0", () => writer.line(`delete(${states}.states, rawSocket)`));
    },
  );
}

/**
 * Emits the per-method dispatch queue.
 *
 * Socket.IO delivers a connection's packets in order, but handing each one to a
 * bare `go handleX(args)` throws that order away. A queue per RPC method keeps
 * the guarantee where it is observable — two calls to the same method run in
 * arrival order — without reintroducing head-of-line blocking across the
 * connection: a blocked handler stalls only its own method's queue.
 */
export function writeEventQueue(writer: GoWriter, side: GoSide): void {
  const queue = generated("eventQueue");

  writer.block(`type ${queue} struct`, () => {
    writer.line("run func([]any)");
    writer.line();
    writer.line("mu      sync.Mutex");
    writer.line("pending [][]any");
    writer.line("running bool");
  });
  writer.line();
  writer.block(`func ${generated("newEventQueue")}(run func([]any)) *${queue}`, () =>
    writer.line(`return &${queue}{run: run}`),
  );
  writer.line();
  writer.line("// push never blocks: the Socket.IO listener must stay free to deliver the");
  writer.line("// next packet even while this method's handler is still running.");
  writer.block(`func (q *${queue}) push(args []any)`, () => {
    writer.line("q.mu.Lock()");
    writer.line("q.pending = append(q.pending, args)");
    writer.block("if q.running", () => {
      writer.line("q.mu.Unlock()");
      writer.line("return");
    });
    writer.line("q.running = true");
    writer.line("q.mu.Unlock()");
    writer.line("go q.drain()");
  });
  writer.line();
  writer.block(`func (q *${queue}) drain()`, () => {
    writer.block("for", () => {
      writer.line("q.mu.Lock()");
      writer.block("if len(q.pending) == 0", () => {
        writer.line("q.running = false");
        writer.line("q.mu.Unlock()");
        writer.line("return");
      });
      writer.line("next := q.pending[0]");
      writer.line("q.pending = q.pending[1:]");
      writer.line("q.mu.Unlock()");
      writer.line("q.run(next)");
    });
  });
  writer.line();
  writer.line("// queuedListener gives one event its own queue. Building it here rather than");
  writer.line(`// in ${side.bindFunction} keeps the registration site free of per-method locals, so the`);
  writer.line("// only contract-derived identifiers in that scope are struct field selectors.");
  writer.block(`func ${generated("queuedListener")}(run func([]any)) func(...any)`, () => {
    writer.line(`queue := ${generated("newEventQueue")}(run)`);
    writer.block("return func(rawArgs ...any)", () => {
      writer.line("queue.push(append([]any(nil), rawArgs...))");
    }, "}");
  });
}

/**
 * Emits the state one inbound event travels through.
 *
 * Everything a per-method handler would otherwise inline — the acknowledgement,
 * the once-guard, the panic recovery, every message string and every reference
 * to an imported package — lives here instead, which is what lets the generated
 * handler bodies stay free of identifiers that could collide with a contract's
 * parameter names.
 */
export function writeInboundCall(writer: GoWriter, side: GoSide): void {
  const call = generated("inboundCall");
  const { q } = side;

  // One OnRpcError registration. The id is what unsubscribe removes by, so a
  // second registration of the same func value stays independently removable.
  writer.block(`type ${generated("errorSubscription")} struct`, () => {
    writer.line("id uint64");
    writer.line(`fn func(*${q}RpcError)`);
  });
  writer.line();

  writer.block(`type ${call} struct`, () => {
    writer.line(`binding *${side.bindingType}`);
    writer.line("method  string");
    writer.line(`ack     ${side.ackType}`);
    writer.line("args    []any");
    writer.line("once    sync.Once");
  });
  writer.line();
  writer.line("// beginInbound splits the acknowledgement callback off the raw argument list");
  writer.line("// and checks arity. It returns nil when the event cannot be carried any");
  writer.line("// further, having already reported why.");
  writer.block(
    `func ${generated("beginInbound")}(b *${side.bindingType}, method string, want int, wantAck bool, rawArgs []any) *${call}`,
    () => {
      writer.line(`pending := &${call}{binding: b, method: method}`);
      writer.line("args := rawArgs");
      writer.block("if wantAck", () => {
        writer.block("if len(args) == 0", () => {
          writer.line(
            `b.${BINDING.emitError}(${q}NewRpcError(${q}CodeInvalidArgument, "missing acknowledgement callback", method, nil))`,
          );
          writer.line("return nil");
        });
        writer.line(`callback, isAck := args[len(args)-1].(${side.ackType})`);
        writer.block("if !isAck", () => {
          writer.line(
            `b.${BINDING.emitError}(${q}NewRpcError(${q}CodeInvalidArgument, "missing acknowledgement callback", method, nil))`,
          );
          writer.line("return nil");
        });
        writer.line("pending.ack = callback");
        writer.line("args = args[:len(args)-1]");
      });
      writer.block("if len(args) != want", () => {
        writer.line(
          `pending.fail(${q}CodeInvalidArgument, fmt.Sprintf("expected %d arguments, got %d", want, len(args)))`,
        );
        writer.line("return nil");
      });
      writer.line("pending.args = args");
      writer.line("return pending");
    },
  );
  writer.line();
  writer.line("// reply answers exactly once. A fire-and-forget call has no acknowledgement");
  writer.line("// slot, so its failures travel on the out-of-band error event instead.");
  writer.block(`func (c *${call}) reply(value any)`, () => {
    writer.block("if c.ack == nil", () => {
      writer.block(`if failure, ok := value.(*${q}RpcError); ok`, () => {
        writer.line(`c.binding.${BINDING.emitError}(failure)`);
      });
      writer.line("return");
    });
    writer.block("c.once.Do(func()", () => writer.line("c.ack([]any{value}, nil)"), "})");
  });
  writer.line();
  writer.block(`func (c *${call}) fail(code ${q}RpcErrorCode, message string)`, () => {
    writer.line(`c.reply(${q}NewRpcError(code, message, c.method, nil))`);
  });
  writer.line();
  writer.line("// recoverPanic is deferred directly by the handler, which is what lets the");
  writer.line("// builtin recover see a panic unwinding through it.");
  writer.block(`func (c *${call}) recoverPanic()`, () => {
    writer.block("if value := recover(); value != nil", () => {
      writer.line(`c.reply(${generated("errorFromPanic")}(value, c.method))`);
    });
  });
  writer.line();
  writer.block(`func (c *${call}) ready() bool`, () => {
    writer.block("if c.binding.Disposed()", () => {
      writer.line(`c.fail(${q}CodeDisposed, ${goString(side.disposedMessage)})`);
      writer.line("return false");
    });
    writer.line("return true");
  });
  writer.line();
  writer.block(`func (c *${call}) decode(index int, target any, name string) bool`, () => {
    writer.block(`if err := ${generated("decodeValue")}(c.args[index], target); err != nil`, () => {
      writer.line(`c.fail(${q}CodeInvalidArgument, fmt.Sprintf("invalid argument %s: %v", name, err))`);
      writer.line("return false");
    });
    writer.line("return true");
  });
  writer.line();
  writer.block(`func (c *${call}) finish(value any, err error)`, () => {
    writer.block("if err != nil", () => {
      writer.line(`c.reply(${generated("errorFromError")}(err, c.method))`);
      writer.line("return");
    });
    if (side.payloadCheck) {
      writer.line("// A reply too large for the server is this handler's failure, not the");
      writer.line("// caller's, so it answers as one instead of closing the connection.");
      writer.block(
        `if failure := c.binding.${BINDING.conn}.checkPayload(c.method, []any{value}); failure != nil`,
        () => {
          writer.line(`failure.Code = ${q}CodeInternalError`);
          writer.line("c.reply(failure)");
          writer.line("return");
        },
      );
    } else {
      writer.block(`if failure := ${generated("ensureEncodable")}(value, c.method); failure != nil`, () => {
        writer.line("c.reply(failure)");
        writer.line("return");
      });
    }
    writer.line("c.reply(value)");
  });
  writer.line();
  writer.block(`func (c *${call}) finishVoid(err error)`, () => {
    writer.block("if err != nil", () => writer.line(`c.reply(${generated("errorFromError")}(err, c.method))`));
  });
}

/**
 * Emits the binding a connected socket is served through.
 *
 * The type's member namespace is the one place where the emitter's own
 * identifiers meet identifiers derived from the contract. Every emitter-owned
 * member therefore sits in `BINDING`, spelled in the reserved namespace, while
 * the contract's own members keep the readable `listen…` / `handle…` spellings
 * that no wire name can turn into an underscore-bearing one. Neither side needs
 * a reserved-word list to stay clear of the other.
 */
export function writeBinding(writer: GoWriter, side: GoSide, methods: readonly RpcMethod[]): void {
  const emitState = generated("socketEmitState");
  const { q, bindingType: binding } = side;
  const listenerFields = [
    ...methods.map(listenerField),
    BINDING.listenRpcError,
    ...(side.disposeOnDisconnect ? [BINDING.listenDisconnect] : []),
  ];

  const writeFields = (fields: readonly (readonly [string, string])[]): void => {
    const width = Math.max(...fields.map(([name]) => name.length));
    for (const [name, type] of fields) writer.line(`${padGoColumn(name, width)}${type}`);
  };

  writer.block(`type ${binding} struct`, () => {
    writeFields([
      [BINDING.socket, side.socketType],
      [BINDING.emitState, `*${emitState}`],
      [BINDING.handler, side.handlerType],
      [BINDING.ctx, "context.Context"],
      [BINDING.cancel, "context.CancelFunc"],
      ...(side.reconnects ? ([[BINDING.conn, `*${side.callerType}`]] as const) : []),
    ]);
    writer.line();
    writeFields([
      [BINDING.mu, "sync.RWMutex"],
      [BINDING.disposed, "bool"],
      [BINDING.errorObserver, `[]${generated("errorSubscription")}`],
      [BINDING.errorObserverSeq, "uint64"],
      [BINDING.disposeOnce, "sync.Once"],
    ]);
    writer.line();
    writeFields(listenerFields.map((name) => [name, "func(...any)"] as const));
  });
  writer.line();
  const connParam = side.reconnects ? `, conn *${side.callerType}` : "";
  writer.block(
    `func ${side.bindFunction}(rawSocket ${side.socketType}, handler ${side.handlerType}${connParam}) (*${binding}, error)`,
    () => {
      writer.block("if rawSocket == nil", () =>
        writer.line(
          `return nil, ${q}NewRpcError(${q}CodeInvalidArgument, "socket must not be nil", ${goString(side.entryPoint)}, nil)`,
        ),
      );
      writer.block("if handler == nil", () =>
        writer.line(
          `return nil, ${q}NewRpcError(${q}CodeInvalidArgument, "handler must not be nil", ${goString(side.entryPoint)}, nil)`,
        ),
      );
      writer.line("ctx, cancel := context.WithCancel(context.Background())");
      writer.line(`binding := &${binding}{`);
      const initializers: (readonly [string, string])[] = [
        [BINDING.socket, "rawSocket"],
        [BINDING.emitState, `${generated("acquireSocketEmitState")}(rawSocket)`],
        [BINDING.handler, "handler"],
        [BINDING.ctx, "ctx"],
        [BINDING.cancel, "cancel"],
        ...(side.reconnects ? ([[BINDING.conn, "conn"]] as const) : []),
      ];
      const keyWidth = Math.max(...initializers.map(([name]) => name.length + 1));
      for (const [name, value] of initializers) {
        writer.line(`\t${padGoColumn(`${name}:`, keyWidth)}${value},`);
      }
      writer.line("}");
      // A contract with no inbound methods registers nothing here, and two
      // blank lines in a row are not gofmt-clean.
      if (methods.length > 0) writer.line();
      for (const method of methods) {
        const field = listenerField(method);
        // A reconnecting side captures the connection a call arrived on before
        // it is queued, so the handler runs under that connection's context.
        const listener = side.reconnects
          ? `${generated("sessionListener")}(conn, binding.${handlerMethod(method)})`
          : `${generated("queuedListener")}(binding.${handlerMethod(method)})`;
        writer.line(`binding.${field} = ${listener}`);
        writer.block(`if err := rawSocket.On(${goString(method.name)}, binding.${field}); err != nil`, () => {
          writer.line("binding.Dispose()");
          writer.line(`return nil, fmt.Errorf("register ${method.name}: %w", err)`);
        });
      }
      writer.line();
      writer.line("// The peer reports a failed fire-and-forget handler out of band, because");
      writer.line("// such a call has no acknowledgement to answer through.");
      writer.line(
        `binding.${BINDING.listenRpcError} = ${generated("queuedListener")}(binding.${BINDING.handleRpcError})`,
      );
      writer.block(
        `if err := rawSocket.On(${q}RPCErrorEvent, binding.${BINDING.listenRpcError}); err != nil`,
        () => {
          writer.line("binding.Dispose()");
          writer.line(`return nil, fmt.Errorf("register %s: %w", ${q}RPCErrorEvent, err)`);
        },
      );
      if (side.disposeOnDisconnect) {
        writer.block(`binding.${BINDING.listenDisconnect} = func(...any)`, () =>
          writer.line("binding.Dispose()"),
        );
        writer.block(
          `if err := rawSocket.On("disconnect", binding.${BINDING.listenDisconnect}); err != nil`,
          () => {
            writer.line("binding.Dispose()");
            writer.line('return nil, fmt.Errorf("register disconnect: %w", err)');
          },
        );
      }
      writer.line("return binding, nil");
    },
  );
  writer.line();
  writer.block(`func (b *${binding}) Context() context.Context`, () =>
    writer.line(`return b.${BINDING.ctx}`),
  );
  writer.line();
  writer.block(`func (b *${binding}) Disposed() bool`, () => {
    writer.line(`b.${BINDING.mu}.RLock()`);
    writer.line(`defer b.${BINDING.mu}.RUnlock()`);
    writer.line(`return b.${BINDING.disposed}`);
  });
  writer.line();
  const reporter = side.peer === "client" ? "a client" : "a server";
  const reportedDirection = side.peer === "client" ? "server-to-client" : "client-to-server";
  writer.line(`// OnRpcError observes the failures the peer reports out of band: ${reporter}`);
  writer.line(`// whose handler for a fire-and-forget ${reportedDirection} call fails has no`);
  writer.line("// acknowledgement to answer through, so it emits the error instead. Without");
  writer.line("// an observer here that report is dropped and this side never learns of it.");
  writer.line("//");
  writer.line("// Observers are additive and run in registration order, matching the");
  writer.line("// TypeScript client's onRpcError. Call the returned function to unsubscribe.");
  writer.block(`func (b *${binding}) OnRpcError(handler func(*${q}RpcError)) func()`, () => {
    writer.block("if b == nil || handler == nil", () => writer.line("return func() {}"));
    writer.line(`b.${BINDING.mu}.Lock()`);
    writer.line(`b.${BINDING.errorObserverSeq}++`);
    writer.line(`id := b.${BINDING.errorObserverSeq}`);
    writer.line(
      `b.${BINDING.errorObserver} = append(b.${BINDING.errorObserver}, ${generated("errorSubscription")}{id: id, fn: handler})`,
    );
    writer.line(`b.${BINDING.mu}.Unlock()`);
    writer.block("return func()", () => {
      writer.line(`b.${BINDING.mu}.Lock()`);
      writer.line(`defer b.${BINDING.mu}.Unlock()`);
      writer.block(`for i, sub := range b.${BINDING.errorObserver}`, () => {
        writer.block("if sub.id == id", () => {
          writer.line(
            `b.${BINDING.errorObserver} = append(b.${BINDING.errorObserver}[:i], b.${BINDING.errorObserver}[i+1:]...)`,
          );
          writer.line("return");
        });
      });
    });
  });
  writer.line();
  writer.block(`func (b *${binding}) ${BINDING.handleRpcError}(rawArgs []any)`, () => {
    writer.line(`b.${BINDING.mu}.RLock()`);
    writer.line("// Snapshot under the lock: an observer is free to subscribe or");
    writer.line("// unsubscribe from inside the callback without deadlocking.");
    writer.line(
      `observers := append([]${generated("errorSubscription")}(nil), b.${BINDING.errorObserver}...)`,
    );
    writer.line(`disposed := b.${BINDING.disposed}`);
    writer.line(`b.${BINDING.mu}.RUnlock()`);
    writer.block("if len(observers) == 0 || disposed || len(rawArgs) == 0", () =>
      writer.line("return"),
    );
    writer.line(`failure, ok := ${generated("decodeRpcError")}(rawArgs[0])`);
    writer.block("if !ok", () => {
      writer.line(
        `failure = ${q}NewRpcError(${q}CodeInternalError, fmt.Sprint(rawArgs[0]), ${q}RPCErrorEvent, nil)`,
      );
    });
    writer.block("for _, sub := range observers", () => {
      writer.line("// An observer that panics must not take the queue goroutine down with");
      writer.line("// it, nor stop the observers registered after it.");
      writer.block("func()", () => {
        writer.block("defer func()", () => writer.line("_ = recover()"), "}()");
        writer.line("sub.fn(failure)");
      }, "}()");
    });
  });
  writer.line();
  writer.block(`func (b *${binding}) Dispose()`, () => {
    writer.block("if b == nil", () => writer.line("return"));
    writer.block(`b.${BINDING.disposeOnce}.Do(func()`, () => {
      writer.block(`if b.${BINDING.emitState} != nil`, () => {
        writer.line(`b.${BINDING.emitState}.mu.Lock()`);
        writer.line(`defer b.${BINDING.emitState}.mu.Unlock()`);
      });
      writer.line(`b.${BINDING.mu}.Lock()`);
      writer.line(`b.${BINDING.disposed} = true`);
      writer.line("// Drop the observers too, so Dispose releases every closure the");
      writer.line("// caller handed over — the same contract as the client's dispose().");
      writer.line(`b.${BINDING.errorObserver} = nil`);
      writer.line(`b.${BINDING.mu}.Unlock()`);
      writer.line(`b.${BINDING.cancel}()`);
      for (const method of methods) {
        const field = listenerField(method);
        writer.block(`if b.${BINDING.socket} != nil && b.${field} != nil`, () => {
          writer.line(`b.${BINDING.socket}.RemoveListener(${goString(method.name)}, b.${field})`);
        });
      }
      writer.block(`if b.${BINDING.socket} != nil && b.${BINDING.listenRpcError} != nil`, () => {
        writer.line(`b.${BINDING.socket}.RemoveListener(${q}RPCErrorEvent, b.${BINDING.listenRpcError})`);
      });
      if (side.disposeOnDisconnect) {
        writer.block(`if b.${BINDING.socket} != nil && b.${BINDING.listenDisconnect} != nil`, () => {
          writer.line(`b.${BINDING.socket}.RemoveListener("disconnect", b.${BINDING.listenDisconnect})`);
        });
      }
      writer.line(`${generated("releaseSocketEmitState")}(b.${BINDING.socket}, b.${BINDING.emitState})`);
    }, "})");
  });
  writer.line();
  writer.block(`func (b *${binding}) ${BINDING.emitError}(err *${q}RpcError)`, () => {
    writer.block(
      `if err == nil || b.${BINDING.socket} == nil || b.${BINDING.emitState} == nil || b.Disposed()`,
      () => writer.line("return"),
    );
    writer.line("// Data is caller-supplied and may not encode; the report must survive it.");
    writer.block(`if ${generated("ensureEncodable")}(err, err.Method) != nil`, () => {
      writer.line(`err = ${q}NewRpcError(err.Code, err.Message, err.Method, nil)`);
    });
    writer.line(`b.${BINDING.emitState}.mu.Lock()`);
    writer.line(`defer b.${BINDING.emitState}.mu.Unlock()`);
    writer.block(`if !b.${BINDING.socket}.Connected() || b.Disposed()`, () => writer.line("return"));
    writer.line(`_ = ${unbuffered(side, `b.${BINDING.socket}`)}.Emit(${q}RPCErrorEvent, err)`);
  });
}

export function writeInboundHandlers(
  writer: GoWriter,
  side: GoSide,
  methods: readonly RpcMethod[],
  declarations: DeclarationScope,
): void {
  for (const method of methods) {
    const wireName = goString(method.name);
    const resultType = resultGoType(method, side.q);
    const wantAck = resultType ? "true" : "false";

    writer.line();
    const parameters = side.reconnects ? "ctx context.Context, rawArgs []any" : "rawArgs []any";
    writer.block(`func (b *${side.bindingType}) ${handlerMethod(method)}(${parameters})`, () => {
      writer.line(
        `call := ${generated("beginInbound")}(b, ${wireName}, ${method.params.length}, ${wantAck}, rawArgs)`,
      );
      writer.block("if call == nil", () => writer.line("return"));
      writer.line("defer call.recoverPanic()");
      writer.block("if !call.ready()", () => writer.line("return"));

      method.params.forEach((param, index) => {
        const local = argumentLocal(index);
        writer.line(`var ${local} ${renderGoType(param.type, side.q)}`);
        writer.block(`if !call.decode(${index}, &${local}, ${goString(param.name)})`, () =>
          writer.line("return"),
        );
      });

      const handle = handlerInterfaceMethod(method);
      if (!resultType) {
        writer.line(`call.finishVoid(b.${BINDING.handler}.${handle}(${handlerCallArguments(method, side)}))`);
        return;
      }

      const empty = emptyCompositeLiteral(method.returnType, declarations, side.q);
      if (!empty) {
        writer.line(`call.finish(b.${BINDING.handler}.${handle}(${handlerCallArguments(method, side)}))`);
        return;
      }

      // The contract promises a slice or a map here, so the handler's nil must
      // not reach a peer typed for an array or an object as JSON null.
      writer.line(`result, err := b.${BINDING.handler}.${handle}(${handlerCallArguments(method, side)})`);
      writer.block("if err == nil && result == nil", () => writer.line(`result = ${empty}`));
      writer.line("call.finish(result, err)");
    });
  }
}

/** The value an acknowledgement callback hands over to the waiting call. */
export function writeAckResult(writer: GoWriter): void {
  writer.block(`type ${generated("ackResult")} struct`, () => {
    writer.line("args []any");
    writer.line("err  error");
  });
}

/**
 * Emits the server's `Client`: its construction and lifetime, which end with the
 * socket's own. The calls it makes are written by `writeCaller`.
 */
function writeServerClient(writer: GoWriter, defaultTimeoutMs: number): void {
  const emitState = generated("socketEmitState");

  writer.block("type ClientOptions struct", () => writer.line("Timeout time.Duration"));
  writer.line();
  writeAckResult(writer);
  writer.line();
  writer.block("type Client struct", () => {
    writer.line("socket    *socket.Socket");
    writer.line(`emitState *${emitState}`);
    writer.line("timeout   time.Duration");
    writer.line();
    writer.line("mu sync.RWMutex");
    writer.line();
    writer.line("disposed     bool");
    writer.line("disconnected bool");
    writer.line("done         chan struct{}");
    writer.line("doneOnce     sync.Once");
    writer.line("releaseOnce  sync.Once");
    writer.line();
    writer.line("listenDisconnect func(...any)");
  });
  writer.line();
  writer.block("func NewClient(rawSocket *socket.Socket, options *ClientOptions) (*Client, error)", () => {
    writer.block("if rawSocket == nil", () =>
      writer.line('return nil, NewRpcError(CodeInvalidArgument, "socket must not be nil", "NewClient", nil)'),
    );
    writer.block("if options != nil && options.Timeout < 0", () => {
      writer.line(
        'return nil, NewRpcError(CodeInvalidArgument, "timeout must not be negative", "NewClient", nil)',
      );
    });
    writer.line(`timeout := ${defaultTimeoutMs} * time.Millisecond`);
    writer.block("if options != nil && options.Timeout > 0", () => writer.line("timeout = options.Timeout"));
    writer.line("client := &Client{");
    writer.line("\tsocket:    rawSocket,");
    writer.line(`\temitState: ${generated("acquireSocketEmitState")}(rawSocket),`);
    writer.line("\ttimeout:   timeout,");
    writer.line("\tdone:      make(chan struct{}),");
    writer.line("}");
    writer.block("client.listenDisconnect = func(...any)", () => writer.line("client.markDisconnected()"));
    writer.block('if err := rawSocket.On("disconnect", client.listenDisconnect); err != nil', () => {
      writer.line("client.releaseEmitState()");
      writer.line('return nil, fmt.Errorf("register disconnect: %w", err)');
    });
    writer.block("if !rawSocket.Connected()", () => {
      writer.line("client.markDisconnected()");
      writer.line('rawSocket.RemoveListener("disconnect", client.listenDisconnect)');
      writer.line('return nil, NewRpcError(CodeDisconnected, "socket is disconnected", "NewClient", nil)');
    });
    writer.line("return client, nil");
  });
  writer.line();
  writer.block("func (c *Client) Socket() *socket.Socket", () => writer.line("return c.socket"));
  writer.line();
  writer.block("func (c *Client) Done() <-chan struct{}", () => writer.line("return c.done"));
  writer.line();
  writer.block("func (c *Client) Connected() bool", () => {
    writer.block("if c == nil", () => writer.line("return false"));
    writer.line("c.mu.RLock()");
    writer.line("defer c.mu.RUnlock()");
    writer.line("return !c.disposed && !c.disconnected && c.socket != nil && c.socket.Connected()");
  });
  writer.line();
  writer.block("func (c *Client) markDisconnected()", () => {
    writer.line("c.emitState.mu.Lock()");
    writer.line("defer c.emitState.mu.Unlock()");
    writer.line("c.mu.Lock()");
    writer.line("c.disconnected = true");
    writer.line("c.mu.Unlock()");
    writer.block("c.doneOnce.Do(func()", () => writer.line("close(c.done)"), "})");
    writer.block("if c.socket != nil && c.listenDisconnect != nil", () => {
      writer.line('c.socket.RemoveListener("disconnect", c.listenDisconnect)');
    });
    writer.line("c.releaseEmitState()");
  });
  writer.line();
  writer.block("func (c *Client) releaseEmitState()", () => {
    writer.block("c.releaseOnce.Do(func()", () => {
      writer.line(`${generated("releaseSocketEmitState")}(c.socket, c.emitState)`);
    }, "})");
  });
  writer.line();
  writer.block("func (c *Client) stateError(method string) *RpcError", () => {
    writer.line("c.mu.RLock()");
    writer.line("defer c.mu.RUnlock()");
    writer.block("if c.disposed", () =>
      writer.line('return NewRpcError(CodeDisposed, "client is disposed", method, nil)'),
    );
    writer.block("if c.disconnected || c.socket == nil || !c.socket.Connected()", () =>
      writer.line('return NewRpcError(CodeDisconnected, "socket is disconnected", method, nil)'),
    );
    writer.line("return nil");
  });
  writer.line();
  writer.block("func (c *Client) Dispose()", () => {
    writer.block("if c == nil", () => writer.line("return"));
    writer.line("c.emitState.mu.Lock()");
    writer.line("defer c.emitState.mu.Unlock()");
    writer.line("c.mu.Lock()");
    writer.block("if c.disposed", () => {
      writer.line("c.mu.Unlock()");
      writer.line("return");
    });
    writer.line("c.disposed = true");
    writer.line("c.mu.Unlock()");
    writer.block("c.doneOnce.Do(func()", () => writer.line("close(c.done)"), "})");
    writer.block("if c.socket != nil && c.listenDisconnect != nil", () => {
      writer.line('c.socket.RemoveListener("disconnect", c.listenDisconnect)');
    });
    writer.line("c.releaseEmitState()");
  });
}

/**
 * Emits the outbound half of a side: context and transport error mapping, the
 * two call shapes, and one `Call…` method per outbound contract method.
 *
 * The caller type supplies `socket`, `emitState`, `timeout`, `done` and
 * `stateError`. On a side whose socket reconnects it also supplies
 * `liveSession`, which hands back a channel closed when the connection the call
 * was sent on drops, and `checkPayload`, which measures the packet against the
 * server's limit.
 */
export function writeCaller(writer: GoWriter, side: GoSide, methods: readonly RpcMethod[]): void {
  const ackResult = generated("ackResult");
  const receiver = generated("c");
  const result = generated("result");
  const failure = generated("err");
  const caller = side.callerType;
  const { q } = side;
  const payloadCheck = (packet: string, plain: string): string =>
    side.payloadCheck ? `c.checkPayload(method, ${packet})` : `${generated("ensureEncodable")}(${plain}, method)`;

  writer.block(`func ${generated("errorFromContext")}(ctx context.Context, method string) *${q}RpcError`, () => {
    writer.block("if ctx == nil", () =>
      writer.line(`return ${q}NewRpcError(${q}CodeInvalidArgument, "context must not be nil", method, nil)`),
    );
    writer.block("if err := ctx.Err(); err != nil", () => {
      writer.block("if errors.Is(err, context.DeadlineExceeded)", () =>
        writer.line(`return ${q}NewRpcError(${q}CodeTimeout, err.Error(), method, nil)`),
      );
      writer.line(`return ${q}NewRpcError(${q}CodeAborted, err.Error(), method, nil)`);
    });
    writer.line("return nil");
  });
  writer.line();
  writer.block(`func ${generated("errorFromTransport")}(err error, method string) *${q}RpcError`, () => {
    writer.block("if err == nil", () => writer.line("return nil"));
    writer.block('if err.Error() == "operation has timed out"', () =>
      writer.line(`return ${q}NewRpcError(${q}CodeTimeout, err.Error(), method, nil)`),
    );
    writer.block('if err.Error() == "socket has been disconnected"', () =>
      writer.line(`return ${q}NewRpcError(${q}CodeDisconnected, err.Error(), method, nil)`),
    );
    writer.line(`return ${q}NewRpcError(${q}CodeInternalError, err.Error(), method, nil)`);
  });
  writer.line();
  writer.line("// emit performs one fire-and-forget call.");
  writer.block(
    `func ${generated("emit")}(c *${caller}, ctx context.Context, method string, args ...any) error`,
    () => {
      writer.block(`if err := ${generated("errorFromContext")}(ctx, method); err != nil`, () =>
        writer.line("return err"),
      );
      writer.block(`if err := ${payloadCheck("append([]any{method}, args...)", "args")}; err != nil`, () =>
        writer.line("return err"),
      );
      writer.line("c.emitState.mu.Lock()");
      writer.line("defer c.emitState.mu.Unlock()");
      writer.block("if err := c.stateError(method); err != nil", () => writer.line("return err"));
      writer.block(`if err := ${unbuffered(side, "c.socket")}.Emit(method, args...); err != nil`, () => {
        writer.line(`return ${generated("errorFromTransport")}(err, method)`);
      });
      writer.line("return nil");
    },
  );
  writer.line();
  writer.line("// request performs one acknowledged call and decodes the answer into target.");
  writer.block(
    `func ${generated("request")}(c *${caller}, ctx context.Context, method string, target any, args ...any) error`,
    () => {
      writer.block(`if err := ${generated("errorFromContext")}(ctx, method); err != nil`, () =>
        writer.line("return err"),
      );
      writer.block(`if err := ${payloadCheck("append([]any{method}, args...)", "args")}; err != nil`, () =>
        writer.line("return err"),
      );
      writer.line(`response := make(chan ${ackResult}, 1)`);
      writer.line("c.emitState.mu.Lock()");
      if (side.reconnects) {
        writer.line("lost, err := c.liveSession(method)");
        writer.block("if err != nil", () => {
          writer.line("c.emitState.mu.Unlock()");
          writer.line("return err");
        });
      } else {
        writer.block("if err := c.stateError(method); err != nil", () => {
          writer.line("c.emitState.mu.Unlock()");
          writer.line("return err");
        });
      }
      writer.line(
        `${unbuffered(side, "c.socket.Timeout(c.timeout)")}.EmitWithAck(method, args...)(func(values []any, err error) {`,
      );
      writer.line("\tselect {");
      writer.line(`\tcase response <- ${ackResult}{args: values, err: err}:`);
      writer.line("\tdefault:");
      writer.line("\t}");
      writer.line("})");
      writer.line("c.emitState.mu.Unlock()");
      writer.line();
      writer.line(`var acknowledged ${ackResult}`);
      writer.line("select {");
      writer.line("case <-ctx.Done():");
      writer.line(`\treturn ${generated("errorFromContext")}(ctx, method)`);
      writer.line("case <-c.done:");
      writer.line("\treturn c.stateError(method)");
      if (side.reconnects) {
        writer.line("case <-lost:");
        writer.line("\t// The connection the call was sent on is gone, and the answer with it.");
        writer.line("\t// Dispose ends that connection too, after closing done, and says why.");
        writer.line("\tselect {");
        writer.line("\tcase <-c.done:");
        writer.line("\t\treturn c.stateError(method)");
        writer.line("\tdefault:");
        writer.line("\t}");
        writer.line(
          `\treturn ${q}NewRpcError(${q}CodeDisconnected, "connection lost before the call was acknowledged", method, nil)`,
        );
      }
      writer.line("case acknowledged = <-response:");
      writer.line("}");
      writer.block("if acknowledged.err != nil", () => {
        writer.line(`return ${generated("errorFromTransport")}(acknowledged.err, method)`);
      });
      writer.block("if len(acknowledged.args) != 1", () => {
        writer.line(
          'message := fmt.Sprintf("expected one acknowledgement value, got %d", len(acknowledged.args))',
        );
        writer.line(`return ${q}NewRpcError(${q}CodeInvalidArgument, message, method, nil)`);
      });
      writer.block(`if failure, ok := ${generated("decodeRpcError")}(acknowledged.args[0]); ok`, () =>
        writer.line("return failure"),
      );
      writer.block(`if err := ${generated("decodeInto")}(acknowledged.args[0], target); err != nil`, () => {
        writer.line('message := fmt.Sprintf("invalid acknowledgement payload: %v", err)');
        writer.line(`return ${q}NewRpcError(${q}CodeInvalidArgument, message, method, nil)`);
      });
      writer.line("return nil");
    },
  );

  // One `Call…` method per outbound call. The prefix keeps a contract's method
  // names clear of both `stdmethods` and the caller's own exported API, so a
  // contract is free to call a method `seek`, `dispose` or `socket`.
  for (const method of methods) {
    const name = clientCallMethod(method);
    const wireName = goString(method.name);
    const params = methodParameters(method, side.apiQ);
    const signatureParams = params ? `ctx context.Context, ${params}` : "ctx context.Context";
    const resultType = resultGoType(method, side.apiQ);
    writer.line();

    if (!resultType) {
      writer.block(`func (${receiver} *${caller}) ${name}(${signatureParams}) error`, () => {
        writer.line(`return ${generated("emit")}(${receiver}, ctx, ${wireName}${outboundArguments(method)})`);
      });
      continue;
    }

    // Named results, so the body never has to spell a type: a contract is free
    // to call a parameter `bool` or `string` without shadowing one here.
    writer.block(
      `func (${receiver} *${caller}) ${name}(${signatureParams}) (${result} ${resultType}, ${failure} error)`,
      () => {
        writer.line(
          `${failure} = ${generated("request")}(${receiver}, ctx, ${wireName}, &${result}${outboundArguments(method)})`,
        );
        writer.line("return");
      },
    );
  }
}

/**
 * Writes an import block, sorted by path within each group as gofmt sorts it.
 * `std` is the standard library group; `external` holds `[alias, path]` pairs.
 */
export function writeImports(
  writer: GoWriter,
  std: readonly string[],
  external: readonly (readonly [string, string])[],
): void {
  writer.line("import (");
  for (const path of [...std].sort()) writer.line(`\t${goString(path)}`);
  writer.line();
  for (const [alias, path] of [...external].sort(([, a], [, b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    writer.line(`\t${alias} ${goString(path)}`);
  }
  writer.line(")");
}

function writeServerFile(schema: RpcSchema, options: ResolvedGoBackendOptions): string {
  const writer = new GoWriter();
  const declarations = declarationsByName(schema);

  writer.line(GENERATED_HEADER.trimEnd());
  writer.line();
  writer.line(`package ${options.packageName}`);
  writer.line();
  writeImports(writer, ["context", "errors", "fmt", "sync", "time"], [["socket", options.socketImport]]);
  writer.line();
  writeSocketEmitState(writer, SERVER_SIDE);
  writer.line();
  writeEventQueue(writer, SERVER_SIDE);
  writer.line();
  const inbound = inboundMethods(schema);
  writeHandlerInterface(writer, SERVER_SIDE, inbound);
  writer.line();
  writeBinding(writer, SERVER_SIDE, inbound);
  writer.line();
  writeInboundCall(writer, SERVER_SIDE);
  writeInboundHandlers(writer, SERVER_SIDE, inbound, declarations);
  writer.line();
  writeServerClient(writer, options.defaultTimeoutMs);
  writer.line();
  writeCaller(writer, SERVER_SIDE, outboundMethods(schema));
  return writer.toString();
}

/** The types file for a package, shared by the server and a colocated client. */
export function generateGoTypes(schema: RpcSchema, packageName: string): string {
  return writeTypesFile(schema, packageName);
}

/**
 * Validate a canonical schema and generate deterministic, gofmt-clean Go source.
 * Throws `GoSchemaError` when the contract has no sound Go projection.
 */
export function generateGo(schema: RpcSchema, options: GoBackendOptions = {}): GeneratedGoFiles {
  validateGoSchema(schema, options);
  const resolved = resolveGoBackendOptions(options);
  return {
    [GO_TYPES_FILENAME]: writeTypesFile(schema, resolved.packageName),
    [GO_SERVER_FILENAME]: writeServerFile(schema, resolved),
  };
}
