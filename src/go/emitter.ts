export const GENERATED_HEADER = `// Code generated by socketrpc-gen. DO NOT EDIT.\n`;

export class GoWriter {
  readonly #lines: string[] = [];
  #indent = 0;

  line(value = ""): void {
    this.#lines.push(value ? `${"\t".repeat(this.#indent)}${value}` : "");
  }

  block(firstLine: string, body: () => void, lastLine = "}"): void {
    this.line(`${firstLine} {`);
    this.#indent += 1;
    body();
    this.#indent -= 1;
    this.line(lastLine);
  }

  toString(): string {
    return `${this.#lines.join("\n")}\n`;
  }
}

/** The Go spelling of a method name, before either API's prefix is applied. */
function methodName(method: RpcMethod): string {
  return exportedIdentifier(method.name);
}

/** The `ServerHandler` method an inbound call is served by. */
function handlerInterfaceMethod(method: RpcMethod): string {
  return handlerMethodName(method.name);
}

/** The `Client` method an outbound call is made through. */
function clientCallMethod(method: RpcMethod): string {
  return clientMethodName(method.name);
}

function paramName(param: RpcParameter): string {
  return localIdentifier(param.name);
}

function fieldName(field: ObjectField): string {
  return exportedIdentifier(field.name);
}

/**
 * What differs between the two Go sides a contract can be generated for.
 *
 * The server and the client run the same machinery in mirror image: each serves
 * the methods its peer calls through a binding of per-method queues, and calls
 * the peer's methods through a caller. The writers below are shared, and this
 * descriptor is the whole of what sets the sides apart — the server's values
 * reproduce the server output byte for byte.
 */
export interface GoSide {
  /**
   * Prefix every function body, and every unexported signature, reaches the
   * error API and the contract types through: `""` inside the types package.
   * A client in its own package spells `"rpc_"`, reaching file-scope aliases of
   * the types package (`writeTypesBridge` in `client.ts`), so no local a body
   * declares can shadow the types package's name.
   */
  readonly q: string;
  /**
   * Selector the exported signatures a developer reads spell contract types
   * with: `""` inside the types package, `"wire."` outside it. A signature's
   * parameters are scoped to its body, so nothing can shadow the name there.
   */
  readonly apiQ: string;
  /** The interface a developer implements, one `Handle…` method per inbound call. */
  readonly handlerType: string;
  /** The type inbound calls are dispatched through. */
  readonly bindingType: string;
  /** The function that constructs `bindingType` and registers its listeners. */
  readonly bindFunction: string;
  /** The exported entry point a construction failure names as its method. */
  readonly entryPoint: string;
  /** The type outbound calls are made through. */
  readonly callerType: string;
  /** The Socket.IO socket both are written against. */
  readonly socketType: string;
  /** The type Socket.IO hands an acknowledgement callback to a listener as. */
  readonly ackType: string;
  /** The peer that reports a failed fire-and-forget handler out of band. */
  readonly peer: "client" | "server";
  /** The answer a call reaching a disposed binding gets. */
  readonly disposedMessage: string;
  /** The binding disposes itself on disconnect, because the socket cannot come back. */
  readonly disposeOnDisconnect: boolean;
  /**
   * The socket reconnects. Every inbound call runs under the context of the
   * connection it arrived on, which that connection's loss cancels; every
   * outbound call fails when the connection it was sent on drops, and is never
   * buffered by the socket for a later one.
   */
  readonly reconnects: boolean;
  /** Outbound packets are measured against the limit the server advertised. */
  readonly payloadCheck: boolean;
}

/**
 * The socket expression a side emits through. A reconnecting socket buffers an
 * emit made while it is disconnected and sends it on the next connection, long
 * after the caller was told the call failed, so that side refuses the buffer
 * for every emit it makes.
 */
function unbuffered(side: GoSide, socket: string): string {
  return side.reconnects ? `${socket}.NoBuffer()` : socket;
}

